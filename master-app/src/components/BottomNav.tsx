const TABS = [
  { path: '/', label: 'Профиль' },
  { path: '/bookings', label: 'Записи' },
  { path: '/clients', label: 'Клиенты' },
  { path: '/income', label: 'Доход' },
]

export default function BottomNav() {
  const location = useLocation()
  const navigate = useNavigate()

  const activeTab = TABS.find((t) =>
    t.path === '/' ? location.pathname === '/' : location.pathname.startsWith(t.path)
  )?.path ?? '/'

  const renderIcon = (path: string, active: boolean) => {
    const c = active ? ACTIVE : INACTIVE
    switch (path) {
      case '/': return <TagUserIcon c={c} />
      case '/bookings': return (
        <div style={{ position: 'relative', display: 'inline-flex' }}>
          <CalendarIcon c={c} />
          <span style={{
            position: 'absolute',
            top: -1,
            right: -3,
            width: 10,
            height: 10,
            borderRadius: '50%',
            background: '#CE4259',
            border: '2px solid var(--color-card)',
          }} />
        </div>
      )
      case '/clients': return <MessageTextIcon c={c} />
      case '/income': return <LocationIcon c={c} />
    }
  }

  return (
    <nav style={{
      position: 'fixed',
      bottom: 0,
      left: 0,
      right: 0,
      height: 60,
      background: 'var(--color-card)',
      borderTop: '1px solid var(--color-border)',
      display: 'flex',
      zIndex: 50,
      paddingBottom: 'env(safe-area-inset-bottom)',
    }}>
      {TABS.map((tab) => {
        const active = activeTab === tab.path
        return (
          <button
            key={tab.path}
            onClick={() => navigate(tab.path)}
            style={{
              flex: 1,
              display: 'flex',
              flexDirection: 'column',
              alignItems: 'center',
              justifyContent: 'center',
              gap: 3,
              background: 'none',
              border: 'none',
              cursor: 'pointer',
              padding: '6px 0',
            }}
          >
            {renderIcon(tab.path, active)}
            <span style={{
              fontSize: 10,
              fontWeight: 500,
              color: active ? ACTIVE : INACTIVE,
            }}>
              {tab.label}
            </span>
          </button>
        )
      })}
    </nav>
  )
}
